/**
 * 修仙天赋。
 *
 * 灵根 / 道胎共 36 个，全部为橙色；
 * 本体不直接进抽卡池（exclusive），由 9 张「灵根玉简」开出：
 * 每张玉简对应一组 4 枚灵根，抽到玉简后再从组内随机显化一枚。
 * 这样既能让 36 枚灵根都以橙色呈现，又不会把橙色池从 22 条撑到 49 条。
 * 其余为随修行阶段解锁的境界天赋。
 */
import type { Talent } from '../talent.types'

type Row = [
    id: number,
    name: string,
    description: string,
    grade: 0 | 1 | 2 | 3,
    effect: Talent['effect'],
    condition?: string,
    group?: string,
    extra?: Partial<Talent>,
]

/** 灵根 / 道胎 / 玉简统一互斥组 */
const ROOT_GROUP = 'root'

/**
 * 灵根条目：只作为玉简的开奖结果存在，不直接进入抽卡池。
 * exclusive 会让 core 的 GradeMap 过滤掉本体，
 * 否则 36 枚灵根会一起挤进橙色池，把其他橙色天赋稀释掉。
 */
function root(
    id: number,
    name: string,
    description: string,
    effect: Talent['effect'],
): Row {
    return [
        id,
        name,
        description,
        3,
        effect,
        undefined,
        ROOT_GROUP,
        { exclusive: true },
    ]
}

/** 灵根玉简：橙色入口，开奖后消耗本体，随机显化同组灵根 */
function vessel(
    id: number,
    name: string,
    description: string,
    members: readonly number[],
): Row {
    return [
        id,
        name,
        description,
        3,
        undefined,
        undefined,
        ROOT_GROUP,
        {
            replacement: {
                talent: members.map(member => [member, 1] as [number, number]),
            },
        },
    ]
}

/** 玉简是消耗品，不会被写进 profile.talents，算收集度分母时要排除 */
export function isRootVessel(talent: Talent): boolean {
    return talent.group === ROOT_GROUP && !!talent.replacement
}

